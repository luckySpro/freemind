import fontkit from "@pdf-lib/fontkit";
import { type Token, type Tokens, marked } from "marked";
import {
  PDFDocument,
  type PDFPage,
  TextRenderingMode,
  degrees,
  popGraphicsState,
  pushGraphicsState,
  rgb,
  setLineWidth,
  setTextRenderingMode,
} from "pdf-lib";
import { getLocale, t } from "../i18n";
import type { MindMapDoc } from "../model/types";
import { engineeringSections } from "./engineeringDocument";
import {
  type PdfSectionDestination,
  addEngineeringPdfNavigation,
  addPdfSectionLink,
} from "./engineeringPdfNavigation";

const FONT_URL = new URL("../assets/fonts/NotoSansCJKsc-Regular.ttf", import.meta.url).href;
const PAGE = [595.28, 841.89] as const;
const MARGIN = 54;
const WIDTH = PAGE[0] - 2 * MARGIN;
const TOP = PAGE[1] - MARGIN;
const BOTTOM = 58;
const INK = rgb(0.12, 0.14, 0.18);
const MUTED = rgb(0.38, 0.41, 0.46);
const ACCENT = rgb(0.12, 0.35, 0.48);
const PALE = rgb(0.95, 0.96, 0.97);

interface Run {
  text: string;
  bold?: boolean;
  italic?: boolean;
  strike?: boolean;
  link?: boolean;
}
type Line = Run[];

let fontBytesPromise: Promise<Uint8Array> | undefined;
function bundledFont(): Promise<Uint8Array> {
  // This URL is generated by Vite from a checked-in asset, not a remote font service.
  fontBytesPromise ??= fetch(FONT_URL)
    .then(async (response) => {
      if (!response.ok) throw new Error(t("writing.readFailed"));
      return new Uint8Array(await response.arrayBuffer());
    })
    .catch((error) => {
      fontBytesPromise = undefined;
      throw error;
    });
  return fontBytesPromise;
}

function inlineRuns(tokens: Token[], style: Omit<Run, "text"> = {}): Run[] {
  return tokens.flatMap((token): Run[] => {
    switch (token.type) {
      case "strong":
        return inlineRuns((token as Tokens.Strong).tokens, { ...style, bold: true });
      case "em":
        return inlineRuns((token as Tokens.Em).tokens, { ...style, italic: true });
      case "del":
        return inlineRuns((token as Tokens.Del).tokens, { ...style, strike: true });
      case "link":
        return inlineRuns((token as Tokens.Link).tokens, { ...style, link: true });
      case "br":
        return [{ text: "\n", ...style }];
      case "image":
        return [];
      case "escape":
      case "codespan":
      case "text":
        if ("tokens" in token && token.tokens) return inlineRuns(token.tokens as Token[], style);
        return [{ text: token.text ?? "", ...style }];
      case "html":
        return [];
      default:
        return [{ text: "text" in token ? String(token.text) : "", ...style }];
    }
  });
}

/** A4 engineering PDF: the same chapter tree as Word, with embedded CJK text, notes,
 * images, tables, exact page numbers, clickable contents and hierarchical bookmarks.
 * fontBytes is injectable for deterministic tests; normal exports use only the bundled asset. */
export async function buildEngineeringPdf(
  doc: MindMapDoc,
  fontBytes?: Uint8Array,
): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  // Keep the full font: fontkit subsets of this CJK font omit glyph outlines in PDF readers.
  const font = await pdf.embedFont(fontBytes ?? (await bundledFont()), { subset: false });
  const characters = new Set(font.getCharacterSet());
  const safeText = (text: string) =>
    Array.from(text.replace(/\t/g, "    ").replace(/\r/g, ""))
      .map((char) => (char === "\n" || characters.has(char.codePointAt(0) ?? 0) ? char : "□"))
      .join("");
  const title = doc.title || doc.root.topic || t("writing.document");
  pdf.setTitle(title);
  pdf.setCreator("FreeMind");
  pdf.setProducer("FreeMind");
  pdf.setSubject(t("writing.description"));
  pdf.setLanguage(getLocale());

  // Wrapping repeatedly measures the same words, characters and table headers.
  // Cache per export so large tables avoid repeating CJK font shaping work.
  const widths = new Map<string, number>();
  const measure = (text: string, size: number) => {
    const key = `${size}:${text}`;
    let width = widths.get(key);
    if (width === undefined) {
      width = font.widthOfTextAtSize(text, size);
      widths.set(key, width);
    }
    return width;
  };
  const words = new Intl.Segmenter(getLocale(), { granularity: "word" });
  const wrap = (runs: Run[], width: number, size: number): Line[] => {
    const lines: Line[] = [[]];
    let used = 0;
    const put = (run: Run) => {
      const line = lines[lines.length - 1];
      const previous = line.at(-1);
      if (
        previous &&
        previous.bold === run.bold &&
        previous.italic === run.italic &&
        previous.strike === run.strike &&
        previous.link === run.link
      )
        previous.text += run.text;
      else line.push({ ...run });
      used += measure(run.text, size);
    };
    const newline = () => {
      lines.push([]);
      used = 0;
    };
    for (const run of runs) {
      const fragments = safeText(run.text).split(/(\n)/);
      for (const fragment of fragments) {
        if (fragment === "\n") {
          newline();
          continue;
        }
        for (const { segment } of words.segment(fragment)) {
          if (used && used + measure(segment, size) > width) newline();
          if (measure(segment, size) > width) {
            for (const char of Array.from(segment)) {
              if (used && used + measure(char, size) > width) newline();
              put({ ...run, text: char });
            }
          } else put({ ...run, text: segment });
        }
      }
    }
    return lines;
  };
  const drawLine = (page: PDFPage, line: Line, startX: number, y: number, size: number) => {
    let x = startX;
    for (const run of line) {
      if (!run.text) continue;
      const width = measure(run.text, size);
      page.pushOperators(pushGraphicsState());
      if (run.bold)
        page.pushOperators(
          setLineWidth(0.25),
          setTextRenderingMode(TextRenderingMode.FillAndOutline),
        );
      page.drawText(run.text, {
        x,
        y,
        size,
        font,
        color: run.link ? ACCENT : INK,
        ...(run.italic ? { xSkew: degrees(10) } : {}),
      });
      page.pushOperators(popGraphicsState());
      if (run.strike)
        page.drawLine({
          start: { x, y: y + size * 0.35 },
          end: { x: x + width, y: y + size * 0.35 },
          thickness: 0.5,
          color: INK,
        });
      x += width;
    }
  };
  const sections = engineeringSections(doc);
  // Plan the contents before body pagination. A long title may consume several rows.
  const tocPlan: { section: number; lines: Line[]; height: number }[][] = [[]];
  let tocRemaining = TOP - 48 - BOTTOM;
  for (const [index, section] of sections.entries()) {
    const indent = (section.level - 1) * 12;
    const lines = wrap([{ text: section.title }], WIDTH - indent - 42, 11);
    const height = lines.length * 17 + 7;
    if (height > tocRemaining && tocPlan.at(-1)?.length) {
      tocPlan.push([]);
      tocRemaining = TOP - 48 - BOTTOM;
    }
    // Unusually long chapter names can span pages; split their TOC rows without losing links.
    for (let start = 0; start < lines.length; ) {
      if (tocRemaining < 24) {
        tocPlan.push([]);
        tocRemaining = TOP - 48 - BOTTOM;
      }
      const take = Math.max(1, Math.min(lines.length - start, Math.floor((tocRemaining - 7) / 17)));
      const segment = lines.slice(start, start + take);
      const rowHeight = segment.length * 17 + 7;
      tocPlan[tocPlan.length - 1].push({ section: index, lines: segment, height: rowHeight });
      tocRemaining -= rowHeight;
      start += take;
    }
  }
  const cover = pdf.addPage([...PAGE]);
  const tocPages = tocPlan.map(() => pdf.addPage([...PAGE]));
  let page = pdf.addPage([...PAGE]);
  let y = TOP;
  const nextPage = () => {
    page = pdf.addPage([...PAGE]);
    y = TOP;
  };
  const ensure = (height: number) => {
    if (y - height < BOTTOM && y < TOP) nextPage();
  };
  const paragraph = (
    runs: Run[],
    size = 11,
    requestedIndent = 0,
    appearance: { code?: boolean; quote?: boolean; gap?: number } = {},
  ) => {
    const indent = Math.min(requestedIndent, WIDTH - 80);
    const x = MARGIN + indent;
    const lines = wrap(runs, WIDTH - indent - (appearance.code ? 12 : 0), size);
    const lineHeight = size * 1.55;
    for (const line of lines) {
      ensure(lineHeight);
      if (appearance.code)
        page.drawRectangle({
          x: x - 4,
          y: y - lineHeight + 3,
          width: WIDTH - indent + 4,
          height: lineHeight,
          color: PALE,
        });
      if (appearance.quote)
        page.drawLine({
          start: { x: x - 8, y: y + 2 },
          end: { x: x - 8, y: y - lineHeight + 2 },
          thickness: 2,
          color: rgb(0.7, 0.75, 0.78),
        });
      drawLine(page, line, x + (appearance.code ? 4 : 0), y - size, size);
      y -= lineHeight;
    }
    y -= appearance.gap ?? 8;
  };
  const image = async (src: string, alt: string) => {
    const match = /^data:image\/(png|jpeg);base64,([a-z0-9+/=\s]+)$/i.exec(src);
    if (!match) {
      paragraph([{ text: t("writing.remoteExport", { alt: alt || t("writing.pasteLocal") }) }]);
      return;
    }
    try {
      const bytes = Uint8Array.from(atob(match[2]), (char) => char.charCodeAt(0));
      const bitmap =
        match[1].toLowerCase() === "png" ? await pdf.embedPng(bytes) : await pdf.embedJpg(bytes);
      const scale = Math.min(1, WIDTH / bitmap.width, (TOP - BOTTOM) / bitmap.height);
      const width = bitmap.width * scale;
      const height = bitmap.height * scale;
      ensure(height + 8);
      page.drawImage(bitmap, { x: MARGIN, y: y - height, width, height });
      y -= height + 10;
    } catch {
      paragraph([{ text: t("writing.invalidImage", { alt: alt || t("writing.image") }) }]);
    }
  };
  const richParagraph = async (
    tokens: Token[],
    indent: number,
    requestedPrefix = "",
    quote = false,
  ) => {
    let prefix = requestedPrefix;
    let pending: Token[] = [];
    const flush = () => {
      if (pending.length || prefix) {
        paragraph([{ text: prefix }, ...inlineRuns(pending)], 11, indent, { quote });
        pending = [];
        prefix = "";
      }
    };
    for (const token of tokens) {
      if (token.type === "image") {
        flush();
        await image((token as Tokens.Image).href, (token as Tokens.Image).text);
      } else pending.push(token);
    }
    flush();
  };
  const table = (token: Tokens.Table, requestedIndent: number) => {
    const indent = Math.min(requestedIndent, WIDTH - 80);
    const columns = token.header.length;
    if (!columns) return;
    const width = (WIDTH - indent) / columns;
    const row = (cells: Tokens.TableCell[], header: boolean, start = 0, count?: number) => {
      const lines = cells.map((cell) =>
        wrap(inlineRuns(cell.tokens, { bold: header }), width - 12, 10),
      );
      const allLines = Math.max(...lines.map((cell) => cell.length));
      const take = count ?? allLines;
      const height = take * 15 + 12;
      for (let c = 0; c < columns; c++) {
        const x = MARGIN + indent + c * width;
        page.drawRectangle({
          x,
          y: y - height,
          width,
          height,
          color: header ? PALE : rgb(1, 1, 1),
          borderColor: rgb(0.75, 0.78, 0.81),
          borderWidth: 0.5,
        });
        for (const [i, line] of (lines[c] ?? []).slice(start, start + take).entries())
          drawLine(page, line, x + 6, y - 16 - i * 15, 10);
      }
      y -= height;
      return allLines;
    };
    const headerHeight =
      Math.max(
        ...token.header.map((cell) => wrap(inlineRuns(cell.tokens), width - 12, 10).length),
      ) *
        15 +
      12;
    // Very tall header cells are treated as a normal spanning row; otherwise repeat the header.
    const repeatHeader = headerHeight < (TOP - BOTTOM) / 3;
    const rows = [token.header, ...token.rows];
    for (const [rowIndex, cells] of rows.entries()) {
      const lineCount = Math.max(
        ...cells.map((cell) => wrap(inlineRuns(cell.tokens), width - 12, 10).length),
      );
      for (let start = 0; start < lineCount; ) {
        const remainingHeight = (lineCount - start) * 15 + 12;
        if (
          y - 27 < BOTTOM ||
          (start === 0 &&
            remainingHeight <= TOP - BOTTOM - (rowIndex && repeatHeader ? headerHeight : 0) &&
            y - remainingHeight < BOTTOM)
        ) {
          nextPage();
          if (rowIndex && repeatHeader) row(token.header, true);
        }
        const take = Math.max(1, Math.min(lineCount - start, Math.floor((y - BOTTOM - 12) / 15)));
        row(cells, rowIndex === 0, start, take);
        start += take;
      }
    }
    y -= 10;
  };
  const blocks = async (tokens: Token[], indent = 0): Promise<void> => {
    for (const token of tokens) {
      switch (token.type) {
        case "space":
          break;
        case "paragraph":
        case "text": {
          const paragraphToken = token as Tokens.Paragraph;
          await richParagraph(paragraphToken.tokens ?? [token], indent);
          break;
        }
        case "heading":
          ensure(42);
          paragraph(inlineRuns((token as Tokens.Heading).tokens, { bold: true }), 12, indent);
          break;
        case "code":
          paragraph([{ text: (token as Tokens.Code).text }], 10, indent + 4, { code: true });
          break;
        case "blockquote":
          // Preserve embedded tables/images in quotes; mark plain quoted paragraphs with a rule.
          for (const child of (token as Tokens.Blockquote).tokens) {
            if (child.type === "paragraph")
              await richParagraph((child as Tokens.Paragraph).tokens, indent + 14, "", true);
            else await blocks([child], indent + 14);
          }
          break;
        case "list": {
          const list = token as Tokens.List;
          for (const [i, item] of list.items.entries()) {
            let prefixed = false;
            const prefix = list.ordered ? `${Number(list.start) + i}. ` : "• ";
            for (const child of item.tokens) {
              if (!prefixed && (child.type === "text" || child.type === "paragraph")) {
                await richParagraph(
                  (child as Tokens.Paragraph).tokens ?? [child],
                  indent + 12,
                  prefix,
                );
                prefixed = true;
              } else await blocks([child], indent + 12);
            }
          }
          break;
        }
        case "table":
          table(token as Tokens.Table, indent);
          break;
        case "hr":
          ensure(14);
          page.drawLine({
            start: { x: MARGIN, y: y - 5 },
            end: { x: MARGIN + WIDTH, y: y - 5 },
            thickness: 0.5,
            color: MUTED,
          });
          y -= 14;
          break;
        case "html":
          paragraph([{ text: t("writing.htmlOmitted") }]);
          break;
        default:
          if ("text" in token) paragraph([{ text: String(token.text) }], 11, indent);
      }
    }
  };
  if (doc.root.note) await blocks(marked.lexer(doc.root.note, { gfm: true }));
  const destinations: PdfSectionDestination[] = [];
  for (const section of sections) {
    const size = section.level === 1 ? 16 : section.level === 2 ? 14 : 12;
    const headingLines = wrap([{ text: section.title, bold: true }], WIDTH, size);
    ensure(Math.min(TOP - BOTTOM, headingLines.length * size * 1.55 + 35));
    y -= 10;
    destinations.push({ title: section.title, level: section.level, page, y });
    paragraph([{ text: section.title, bold: true }], size);
    if (section.node.note) await blocks(marked.lexer(section.node.note, { gfm: true }));
    if (section.node.image) await image(section.node.image.url, section.node.topic);
  }
  // A cover title can itself be long. Keep it inside its reserved area rather than clipping it.
  let coverSize = 26;
  while (coverSize > 8 && wrap([{ text: title }], WIDTH, coverSize).length * coverSize * 1.5 > 550)
    coverSize -= 1;
  let coverY = PAGE[1] - 160;
  for (const line of wrap([{ text: title }], WIDTH, coverSize)) {
    drawLine(cover, line, MARGIN, coverY, coverSize);
    coverY -= coverSize * 1.5;
  }
  cover.drawText(safeText(t("writing.document")), {
    x: MARGIN,
    y: Math.max(80, coverY - 36),
    size: 12,
    font,
    color: MUTED,
  });
  for (const [tocIndex, rows] of tocPlan.entries()) {
    const toc = tocPages[tocIndex];
    drawLine(toc, [{ text: t("writing.contents"), bold: true }], MARGIN, TOP - 18, 18);
    let rowY = TOP - 48;
    for (const row of rows) {
      const destination = destinations[row.section];
      const indent = (destination.level - 1) * 12;
      const startY = rowY;
      for (const line of row.lines) {
        drawLine(toc, line, MARGIN + indent, rowY - 11, 11);
        rowY -= 17;
      }
      const number = String(pdf.getPages().indexOf(destination.page) + 1);
      const numberWidth = measure(number, 11);
      toc.drawText(number, {
        x: PAGE[0] - MARGIN - numberWidth,
        y: startY - 11,
        font,
        size: 11,
        color: MUTED,
      });
      addPdfSectionLink(
        pdf,
        toc,
        [MARGIN + indent, rowY - 4, PAGE[0] - MARGIN, startY + 3],
        destination,
      );
      rowY -= 7;
    }
  }
  addEngineeringPdfNavigation(pdf, destinations);
  for (const [index, pdfPage] of pdf.getPages().entries()) {
    const text = `${index + 1} / ${pdf.getPageCount()}`;
    pdfPage.drawText(text, {
      x: (PAGE[0] - measure(text, 9)) / 2,
      y: 29,
      size: 9,
      font,
      color: MUTED,
    });
  }
  return pdf.save();
}
